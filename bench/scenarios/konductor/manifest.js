'use strict';

// The run-level manifest (B-009): bench/scenarios/konductor/manifest.json lists every scenario id of the pack with the
// levels (lite, standard, full) that levels.js picks it for, plus each level's list hash. Generated, never typed by hand;
// task files stay untouched. Free: reads task files only.
//   node bench/scenarios/konductor/manifest.js           write manifest.json
//   node bench/scenarios/konductor/manifest.js --check   change nothing; exit 1 when the file differs from levels.js

const fs = require('node:fs');
const path = require('node:path');
const { selectLevel, LEVELS } = require('./levels.js');
const { loadTasks, loadSuite, suiteExtraDirs } = require('../../runner/lib/tasks.js');

const MANIFEST_FILE = path.join(__dirname, 'manifest.json');

/** The task objects of the `pack` suite, as `run --suite pack --level` sees them. */
function packTasks() {
  const all = loadTasks(undefined, { extraDirs: suiteExtraDirs('pack') });
  return loadSuite('pack', all).taskIds.map((id) => all.get(id));
}

/** The manifest object for `tasks`: { _comment, listHashes: { level: hash }, scenarios: { id: [levels] } }. */
function buildManifest(tasks = packTasks()) {
  const scenarios = Object.fromEntries(tasks.map((t) => t.id).sort().map((id) => [id, []]));
  const listHashes = {};
  for (const level of LEVELS) {
    const sel = selectLevel({ level, tasks });
    listHashes[level] = sel.listHash;
    for (const id of sel.ids) scenarios[id].push(level);
  }
  return {
    _comment: 'Generated by bench/scenarios/konductor/manifest.js from levels.js: each scenario id with its run levels. Do not edit by hand.',
    listHashes,
    scenarios,
  };
}

/** JSON text with one scenario per line, so a diff shows exactly which scenarios changed level. */
function render(m) {
  const ids = Object.keys(m.scenarios).sort();
  const rows = ids.map((id, i) => `    ${JSON.stringify(id)}: ${JSON.stringify(m.scenarios[id])}${i < ids.length - 1 ? ',' : ''}`);
  const head = JSON.stringify({ _comment: m._comment, listHashes: m.listHashes }, null, 2).slice(0, -2);
  return `${head},\n  "scenarios": {\n${rows.join('\n')}\n  }\n}\n`;
}

function main(argv) {
  const m = buildManifest();
  const want = render(m);
  const rel = path.relative(path.join(__dirname, '..', '..', '..'), MANIFEST_FILE);
  if (argv.includes('--check')) {
    if (fs.existsSync(MANIFEST_FILE) && fs.readFileSync(MANIFEST_FILE, 'utf8') === want) { console.log(`ok: ${rel} matches levels.js`); return 0; }
    console.log(`${rel} differs from levels.js; run node bench/scenarios/konductor/manifest.js`);
    return 1;
  }
  fs.writeFileSync(MANIFEST_FILE, want);
  console.log(`wrote ${rel}: ${Object.keys(m.scenarios).length} scenario(s)`);
  return 0;
}

if (require.main === module) process.exitCode = main(process.argv.slice(2));

module.exports = { buildManifest, packTasks, render, MANIFEST_FILE };
