'use strict';

// The `pack` suite file (bench/suites/pack.json), generated from the scenario pack's task files: every batch directory
// that holds tasks as an extra task directory, every task id, and each task's run levels (lite, standard, full) with the
// three list hashes, from the one selection rule in konductor/levels.js (B-009). `run --suite pack --level ...` picks
// with that same rule, so the levels here are a generated record, never typed by hand. Free: reads task files only.
//   node bench/scenarios/pack-suite.js           write bench/suites/pack.json
//   node bench/scenarios/pack-suite.js --check   change nothing; exit 1 when the file differs from the task files

const fs = require('node:fs');
const path = require('node:path');
const { loadTaskFiles } = require('./files.js');
const { selectLevel, LEVELS } = require('./konductor/levels.js');

const PACK_DIR = __dirname;
const BENCH_DIR = path.join(__dirname, '..');
const SUITE_FILE = path.join(BENCH_DIR, 'suites', 'pack.json');

/** { listHashes: { level: hash }, levels: { id: [levels] } } for the task objects `tasks`, from levels.js. */
function levelTags(tasks) {
  const levels = Object.fromEntries(tasks.map((t) => t.id).sort().map((id) => [id, []]));
  const listHashes = {};
  for (const level of LEVELS) {
    const sel = selectLevel({ level, tasks });
    listHashes[level] = sel.listHash;
    for (const id of sel.ids) levels[id].push(level);
  }
  return { listHashes, levels };
}

/** The suite object for the pack under `packDir`: { extraTasks, tasks, listHashes, levels, arms, replicates, parallel, judges }. */
function packSuite(packDir = PACK_DIR, benchDir = BENCH_DIR) {
  const items = loadTaskFiles(packDir);
  const dirs = [...new Set(items.map(({ file }) => path.relative(benchDir, path.dirname(file)).split(path.sep).join('/')))].sort();
  return {
    _comment: 'Generated by bench/scenarios/pack-suite.js from the scenario pack; do not edit by hand. Run with --level to pick tasks; levels lists each task\'s run levels from levels.js.',
    extraTasks: dirs,
    tasks: items.map(({ task }) => task.id).sort(),
    ...levelTags(items.map(({ task }) => task)),
    arms: ['vanilla', 'main'],
    replicates: 1,
    parallel: 1,
    judges: ['gpt-5.6-luna', 'deepseek-3.2', 'glm-5'],
  };
}

// One line per task in `levels`: an array of level names only is folded back onto its line.
const LEVEL_ARRAY = /\[\n\s+"(?:lite|standard|full)"(?:,\n\s+"(?:lite|standard|full)")*\n\s+\]/g;
const render = (suite) => `${JSON.stringify(suite, null, 2).replace(LEVEL_ARRAY, (m) => JSON.stringify(JSON.parse(m)))}\n`;

function main(argv) {
  const want = render(packSuite());
  const have = fs.existsSync(SUITE_FILE) ? fs.readFileSync(SUITE_FILE, 'utf8') : null;
  if (argv.includes('--check')) {
    if (have === want) { console.log('ok: bench/suites/pack.json matches the pack'); return 0; }
    console.log('bench/suites/pack.json differs from the pack; run `node bench/scenarios/pack-suite.js`');
    return 1;
  }
  fs.writeFileSync(SUITE_FILE, want);
  console.log(`wrote bench/suites/pack.json: ${packSuite().tasks.length} task(s)`);
  return 0;
}

if (require.main === module) process.exitCode = main(process.argv.slice(2));

module.exports = { packSuite, levelTags, render, SUITE_FILE };
