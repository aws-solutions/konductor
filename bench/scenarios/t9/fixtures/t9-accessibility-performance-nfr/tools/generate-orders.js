// Writes data/orders.js. The output is deterministic (seeded), so re-running it
// on the same script gives the same file.
//   node tools/generate-orders.js
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const COUNT = 1500;
const LAST_DAY = Date.UTC(2025, 5, 20);
const FIRST_DAY = Date.UTC(2023, 0, 3);

function mulberry32(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const rand = mulberry32(20250620);
const pick = (list) => list[Math.floor(rand() * list.length)];
const between = (lo, hi) => lo + Math.floor(rand() * (hi - lo + 1));

