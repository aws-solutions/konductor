const pad = (n, w = 2) => String(n).padStart(w, '0');
const isoDay = (ms) => {
  const d = new Date(ms);
  return `${d.getUTCFullYear()}-${pad(d.getUTCMonth() + 1)}-${pad(d.getUTCDate())}`;
};

function statusFor(ageDays) {
  const r = rand();
  if (ageDays <= 150) {
    if (r < 0.2) return 'processing';
    if (r < 0.42) return 'shipped';
    return 'delivered';
  }
  if (r < 0.06) return 'processing';
  if (r < 0.12) return 'shipped';
  return 'delivered';
}

const days = [];
for (let i = 0; i < COUNT; i += 1) {
  // A little more traffic in recent months than in the first year.
  const skew = Math.pow(rand(), 0.8);
  days.push(FIRST_DAY + Math.floor(skew * ((LAST_DAY - FIRST_DAY) / 86400000)) * 86400000);
}
days.sort((a, b) => b - a);

const orders = days.map((ms, index) => {
  const ageDays = Math.round((LAST_DAY - ms) / 86400000);
  const customer = rand() < 0.09 ? pick(COMPANIES) : `${pick(FIRST)} ${pick(LAST)}`;
  const lines = between(1, 4);
  const items = [];
  for (let n = 0; n < lines; n += 1) {
    const [sku, name, price] = pick(CATALOG);
    if (!items.some((x) => x.sku === sku)) items.push({ sku, name, qty: between(1, 3), price });
  }
  const total = items.reduce((sum, x) => sum + x.qty * x.price, 0);
  return { id: `TW-${10000 + COUNT - index}`, date: isoDay(ms), customer, city: pick(CITIES), status: statusFor(ageDays), total, items };
});

const body = orders.map((o) => `  ${JSON.stringify(o)}`).join(',\n');
const text = `// Generated by tools/generate-orders.js. Re-run the script instead of editing this file.\nexport const orders = [\n${body},\n];\n`;
const target = fileURLToPath(new URL('../data/orders.js', import.meta.url));
writeFileSync(target, text);
console.log(`wrote ${orders.length} orders to data/orders.js`);
